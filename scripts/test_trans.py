def translate_lang(text):
    if not text:
        return 'Official Language'
    out = text
    # Replace sorted by length desc
    for es, en in sorted(LANG_MAP.items(), key=lambda x: -len(x[0])):
        out = re.sub(r'\b' + re.escape(es) + r'\b', en, out, flags=re.IGNORECASE)
    return out

